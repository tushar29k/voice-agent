"""Generate evals/adversarial_variants.yaml from the adversarial.yaml seeds.

Offline, one-shot generation: CI never runs this — the output is a
checked-in YAML file, diff-reviewed like a lockfile before committing.
The deterministic mutations come from mutations.MUTATIONS; each
mutable seed's payload turn is replaced by its mutated text, and each
seed also gets a split_payload case (the payload delivered as two
consecutive caller turns — neither half needs to trip the state
machine on its own).

Only utterance-carried seeds are mutated (families injection and
confirm_bypass, flagged `mutable: true` in the seed file). Probe and
indirect seeds are not prose payloads — they are store states and
questions about them — so they stay seeds-only, which is stated in
the report rather than papered over. Benign near-miss controls are
hand-seeded in near_miss_controls.yaml and copied in verbatim.

Dedup mirrors the sibling generator: exact hash on
whitespace-collapsed text (case preserved — case is the entire
mutation for all_caps) across all variants and against the seeds,
then a per-seed token-set Jaccard >= 0.9 near-dup filter against the
seed's already-kept variants. The output
header stamps the seed file's sha256; regeneration is byte-identical
(same seeds -> same file), which the build verifies by running this
twice and comparing hashes.

    python3 evals/generate_variants.py
"""
import hashlib
import os
import sys

import yaml

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import mutations  # noqa: E402

GENERATOR_VERSION = 1
HERE = os.path.dirname(os.path.abspath(__file__))
SEEDS_PATH = os.path.join(HERE, "adversarial.yaml")
CONTROLS_PATH = os.path.join(HERE, "near_miss_controls.yaml")
OUT_PATH = os.path.join(HERE, "adversarial_variants.yaml")


def _norm(text):
    return " ".join(text.split())


def _case_key(case):
    key = _norm("\n".join(case["turns"]))
    if case.get("mutation") == "split_payload":
        # the two halves rejoin to the seed's exact text — placement
        # across two turns is the entire mutation, so it rides in the
        # key (same fix as the sibling generator)
        key += " #split"
    return key


def _tokens(text):
    # case-sensitive on purpose: lowercasing would make all_caps a
    # near-dup of its own seed and dedup away the mutation being tested
    return set(_norm(text).split())


def _jaccard(a, b):
    if not a or not b:
        return 0.0
    return len(a & b) / len(a | b)


def build():
    with open(SEEDS_PATH, "rb") as f:
        seed_bytes = f.read()
    seeds = yaml.safe_load(seed_bytes.decode())["cases"]
    controls = yaml.safe_load(open(CONTROLS_PATH))["cases"]

    seen = {_case_key(c) for c in seeds}
    out = []
    for seed in seeds:
        if not seed.get("mutable"):
            continue
        pidx = seed["payload_turn"]
        payload = seed["turns"][pidx]
        kept_sibling_tokens = []
        candidates = []
        for name, fn in mutations.MUTATIONS.items():
            turns = list(seed["turns"])
            turns[pidx] = fn(payload)
            candidates.append((turns, name))
        first, second = mutations.split_payload(payload)
        turns = (list(seed["turns"][:pidx]) + [first, second]
                 + list(seed["turns"][pidx + 1:]))
        candidates.append((turns, "split_payload"))
        for turns, name in candidates:
            case = _variant(seed, turns, name)
            key = _case_key(case)
            if key in seen:
                continue
            toks = _tokens(turns[pidx])
            if any(_jaccard(toks, s) >= 0.9 for s in kept_sibling_tokens):
                continue
            seen.add(key)
            kept_sibling_tokens.append(toks)
            out.append(case)

    for ctl in controls:
        case = dict(ctl)
        case["seed_id"] = ctl["id"]
        case["mutation"] = "hand_seeded"
        out.append(case)

    header = (
        "# GENERATED by evals/generate_variants.py (v%d) — do not hand-edit.\n"
        "# seeds: evals/adversarial.yaml sha256:%s\n"
        "# controls: evals/near_miss_controls.yaml (copied verbatim)\n"
        % (GENERATOR_VERSION, hashlib.sha256(seed_bytes).hexdigest()))
    body = yaml.safe_dump({"cases": out}, allow_unicode=True,
                          sort_keys=False, width=4096)
    return header + body


def _variant(seed, turns, mutation_name):
    case = {"id": f"{seed['id']}__{mutation_name}",
            "seed_id": seed["id"],
            "mutation": mutation_name}
    for k, v in seed.items():
        if k not in ("id", "mutable", "payload_turn"):
            case[k] = v
    case["turns"] = turns
    return case


def main():
    text = build()
    with open(OUT_PATH, "w") as f:
        f.write(text)
    cases = yaml.safe_load(text)["cases"]
    attacks = [c for c in cases if c.get("type") != "control"]
    print(f"wrote {OUT_PATH}: {len(cases)} cases "
          f"({len(attacks)} attack variants, "
          f"{len(cases) - len(attacks)} controls)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
